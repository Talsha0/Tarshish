-- Tarshish / FindHub schema for PostgreSQL (Supabase).
--
-- The engine applies this file by itself the first time it connects to an empty database
-- (core/database.py, Database.initialize), so running it by hand is optional. To create the
-- tables up front instead, paste it into the Supabase SQL editor and run it once: every
-- statement is idempotent.
--
-- It mirrors the SQLite schema in core/database.py column for column. Timestamps stay
-- UTC ISO-8601 TEXT (they sort chronologically) and flags stay 0/1 INTEGERs so that the
-- same queries run on both databases.
--
-- Row Level Security is switched ON for every table with NO policies. The engine, the
-- storefront API and the dashboard connect with the database connection string (the
-- `postgres` role, which bypasses RLS), while Supabase's public REST/GraphQL APIs — reachable
-- with the anon key that ships in every Supabase project — get no rows at all.

CREATE TABLE IF NOT EXISTS tarshish_meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS categories (
    category_id            TEXT PRIMARY KEY,
    display_name_en        TEXT NOT NULL,
    display_name_he        TEXT NOT NULL DEFAULT '',
    temu_search_json       TEXT,
    aliexpress_search_json TEXT,
    min_rating             DOUBLE PRECISION NOT NULL DEFAULT 0,
    min_orders             INTEGER NOT NULL DEFAULT 0,
    enabled                INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    created_at             TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS content_profiles (
    content_type    TEXT PRIMARY KEY,
    platform        TEXT NOT NULL,
    generator       TEXT NOT NULL,
    llm_model       TEXT NOT NULL DEFAULT 'mock',
    publish_format  TEXT,
    tone            TEXT,
    prompt_template TEXT,
    enabled         INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    created_at      TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS social_accounts (
    category_id        TEXT NOT NULL,
    language           TEXT NOT NULL,
    platform           TEXT NOT NULL,
    account_handle     TEXT NOT NULL,
    token_env_var      TEXT,
    account_id_env_var TEXT,
    platform_metadata_json TEXT,
    enabled            INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    created_at         TEXT NOT NULL,
    PRIMARY KEY (category_id, language, platform)
);
-- Schema v4: non-secret platform identifiers (app_id, business_account_id, chat_id …) per account.
ALTER TABLE social_accounts ADD COLUMN IF NOT EXISTS platform_metadata_json TEXT;

CREATE TABLE IF NOT EXISTS products (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id         TEXT NOT NULL,
    source              TEXT NOT NULL,
    canonical_hash      TEXT NOT NULL,
    category            TEXT,
    title               TEXT NOT NULL,
    price               DOUBLE PRECISION NOT NULL,
    currency            TEXT NOT NULL DEFAULT 'ILS',
    affiliate_url       TEXT NOT NULL,
    created_at          TEXT NOT NULL,
    raw_url             TEXT,
    video_url           TEXT,
    title_he            TEXT,
    original_price      DOUBLE PRECISION,
    discount_percent    INTEGER,
    rating              DOUBLE PRECISION,
    orders_count        INTEGER,
    image_urls_json     TEXT NOT NULL DEFAULT '[]',
    coupon_code         TEXT,
    is_flash_sale       INTEGER NOT NULL DEFAULT 0,
    stock_urgency_label TEXT,
    UNIQUE (source, external_id)
);
CREATE INDEX IF NOT EXISTS idx_products_canonical_hash ON products (canonical_hash);
CREATE INDEX IF NOT EXISTS idx_products_category ON products (category);
-- Schema v5: offline demo rows (temu_mock, aliexpress_mock) are flagged so live content never uses them.
ALTER TABLE products ADD COLUMN IF NOT EXISTS is_mock INTEGER NOT NULL DEFAULT 0;
UPDATE products SET is_mock = 1 WHERE is_mock = 0 AND LOWER(source) LIKE '%mock%';

CREATE TABLE IF NOT EXISTS publications (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id         TEXT NOT NULL,
    product_id          BIGINT NOT NULL REFERENCES products (id),
    category            TEXT,
    language            TEXT,
    content_format      TEXT,
    account_platform    TEXT,
    platform            TEXT NOT NULL,
    target_page         TEXT NOT NULL DEFAULT 'default',
    content_type        TEXT NOT NULL CHECK (content_type IN ('text', 'video')),
    status              TEXT NOT NULL CHECK (status IN ('PENDING', 'QUEUED', 'PUBLISHED', 'FAILED')),
    caption             TEXT NOT NULL,
    media_uri           TEXT,
    model_used          TEXT NOT NULL,
    generation_cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
    platform_post_id    TEXT,
    scheduled_for       TEXT,
    published_at        TEXT,
    error_message       TEXT,
    content_json        TEXT NOT NULL,
    target_json         TEXT NOT NULL DEFAULT '{}',
    attempts            INTEGER NOT NULL DEFAULT 0,
    created_at          TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_publications_queue    ON publications (status, scheduled_for);
CREATE INDEX IF NOT EXISTS idx_publications_pipeline ON publications (pipeline_id, product_id);
CREATE INDEX IF NOT EXISTS idx_publications_target   ON publications (platform, target_page, status);
CREATE INDEX IF NOT EXISTS idx_publications_account
    ON publications (category, language, account_platform, content_format, product_id);

CREATE TABLE IF NOT EXISTS metrics_snapshots (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publication_id BIGINT NOT NULL REFERENCES publications (id) ON DELETE CASCADE,
    views          INTEGER NOT NULL DEFAULT 0,
    clicks         INTEGER NOT NULL DEFAULT 0,
    conversions    INTEGER NOT NULL DEFAULT 0,
    revenue_usd    DOUBLE PRECISION NOT NULL DEFAULT 0,
    recorded_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_metrics_publication ON metrics_snapshots (publication_id, recorded_at);

CREATE TABLE IF NOT EXISTS ai_usage (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id         TEXT NOT NULL,
    product_ref         TEXT NOT NULL,
    model_used          TEXT NOT NULL,
    tokens_input        INTEGER NOT NULL DEFAULT 0,
    tokens_output       INTEGER NOT NULL DEFAULT 0,
    generation_cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
    created_at          TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ai_usage_created ON ai_usage (created_at);

CREATE TABLE IF NOT EXISTS click_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT NOT NULL REFERENCES products (id),
    category      TEXT NOT NULL,
    source        TEXT NOT NULL,
    language      TEXT NOT NULL,
    referrer_path TEXT NOT NULL DEFAULT '',
    clicked_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_click_events_time     ON click_events (clicked_at);
CREATE INDEX IF NOT EXISTS idx_click_events_product  ON click_events (product_id, clicked_at);
CREATE INDEX IF NOT EXISTS idx_click_events_category ON click_events (category, source);

-- Schema v4: background jobs started from the web admin, with their console output.
CREATE TABLE IF NOT EXISTS job_runs (
    id           TEXT PRIMARY KEY,
    kind         TEXT NOT NULL,
    params_json  TEXT NOT NULL DEFAULT '{}',
    argv_json    TEXT NOT NULL DEFAULT '[]',
    status       TEXT NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    exit_code    INTEGER,
    log_text     TEXT NOT NULL DEFAULT '',
    error        TEXT,
    created_at   TEXT NOT NULL,
    started_at   TEXT,
    finished_at  TEXT
);
CREATE INDEX IF NOT EXISTS idx_job_runs_created ON job_runs (created_at);

-- Schema v5: branded promotional assets generated from real products (plugins/generators/content_generator.py).
CREATE TABLE IF NOT EXISTS generated_assets (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id             BIGINT NOT NULL REFERENCES products (id),
    category_id            TEXT NOT NULL,
    language               TEXT NOT NULL,
    platform               TEXT NOT NULL CHECK (platform IN ('telegram', 'instagram', 'tiktok')),
    content_type           TEXT NOT NULL CHECK (content_type IN ('telegram_post', 'instagram_post', 'instagram_story',
                                                                 'instagram_reel', 'tiktok_post')),
    target_account_id      TEXT,
    target_account_handle  TEXT,
    generated_text         TEXT NOT NULL,
    generated_image_path   TEXT,
    generated_image_url    TEXT,
    links_payload_json     TEXT NOT NULL DEFAULT '{}',
    llm_model_used         TEXT NOT NULL,
    status                 TEXT NOT NULL CHECK (status IN ('DRAFT', 'QUEUED', 'PUBLISHED', 'FAILED')),
    platform_post_id       TEXT,
    error_message          TEXT,
    attempts               INTEGER NOT NULL DEFAULT 0,
    locked_at              TEXT,
    published_at           TEXT,
    created_at             TEXT NOT NULL,
    updated_at             TEXT
);
CREATE INDEX IF NOT EXISTS idx_generated_assets_status  ON generated_assets (status, created_at);
CREATE INDEX IF NOT EXISTS idx_generated_assets_product ON generated_assets (product_id, language, content_type);

-- Lock the tables away from Supabase's public APIs (see the header).
ALTER TABLE tarshish_meta     ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories        ENABLE ROW LEVEL SECURITY;
ALTER TABLE content_profiles  ENABLE ROW LEVEL SECURITY;
ALTER TABLE social_accounts   ENABLE ROW LEVEL SECURITY;
ALTER TABLE products          ENABLE ROW LEVEL SECURITY;
ALTER TABLE publications      ENABLE ROW LEVEL SECURITY;
ALTER TABLE metrics_snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_usage          ENABLE ROW LEVEL SECURITY;
ALTER TABLE click_events      ENABLE ROW LEVEL SECURITY;
ALTER TABLE job_runs          ENABLE ROW LEVEL SECURITY;
ALTER TABLE generated_assets  ENABLE ROW LEVEL SECURITY;
